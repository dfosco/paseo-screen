// Embeds helper/main.swift into server/helper-source.generated.ts.
// Plugin bundles are evaluated from memory, so the server cannot read files beside itself at runtime.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const root = new URL("..", import.meta.url);
const source = readFileSync(new URL("helper/main.swift", root), "utf8");
const hash = createHash("sha256").update(source).digest("hex").slice(0, 16);
const output = `// Generated by scripts/embed-helper.mjs from helper/main.swift. Do not edit.
export const HELPER_SOURCE_HASH = ${JSON.stringify(hash)};
export const HELPER_SOURCE = ${JSON.stringify(source)};
`;
writeFileSync(new URL("server/helper-source.generated.ts", root), output);
console.log(`embedded helper/main.swift (${source.length} bytes, ${hash})`);
